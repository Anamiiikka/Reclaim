"""Render report.json as markdown for the README and the pitch.

    python evaluation/render_report.py > evaluation/RESULTS.md
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rupees(paise: int) -> str:
    return f"Rs {paise / 100:,.0f}"


def main() -> None:
    report = json.loads((ROOT / "evaluation" / "report.json").read_text(encoding="utf-8"))
    model = json.loads((ROOT / "evaluation" / "model.json").read_text(encoding="utf-8"))
    verified = report["verified"]
    scenarios = report["simulated"]["scenarios"]
    central = scenarios["central"]

    print("# Results\n")
    print("Generated by `evaluation/evaluate.py`. Reproducible from seed 20260831.\n")

    print("## Verified\n")
    print("Measured against ground truth. These hold regardless of what any customer")
    print("would have done, and they are the claims made without qualification.\n")

    violations = sum(verified["policy_violations"].values())
    coverage = verified["coverage"]
    print("| Metric | Value |")
    print("|---|---|")
    print(f"| Cases decided | {coverage['cases']:,} |")
    print(f"| **Policy violations** | **{violations}** |")
    print(f"| Customers contacted | {coverage['contacted']:,} ({coverage['contact_rate']:.1%}) |")
    print(f"| Suppressed by policy | {coverage['suppressed']:,} |")
    print(f"| Escalated to a human | {coverage['escalated']:,} |")
    print(f"| Held for merchant approval | {coverage['held_for_approval']:,} |")
    ambiguous = verified["diagnosis"]["ambiguous_subset"]
    print(f"| Ambiguous-case diagnosis accuracy | {ambiguous['accuracy']:.1%} (n={ambiguous['n']}) |")
    print(f"| Model AUC, held-out | {model['metrics']['heldout']['auc']:.3f} |")
    print()

    print("Every violation count is zero across the full corpus:\n")
    for rule, count in verified["policy_violations"].items():
        print(f"- `{rule}`: **{count}**")
    print()

    print("### On diagnosis accuracy\n")
    print(f"Overall accuracy is {verified['diagnosis']['accuracy']:.1%}, and that number is not a result.")
    print("The generator writes a gateway failure code and the engine maps that same code")
    print("back through the same table, so agreement is arithmetic rather than inference.")
    print(f"\nThe meaningful number is **{ambiguous['accuracy']:.1%} on {ambiguous['n']} genuinely ambiguous cases** --")
    print("unrecognised gateway codes where the engine has to fall back to heuristics.")
    print("The sample is small, and that is stated rather than hidden.\n")

    print("## Simulated\n")
    print("These depend entirely on the assumptions in [RESPONSE_MODEL.md](../RESPONSE_MODEL.md).")
    print("They are reported against a randomised control arm that receives no contact,")
    print("across three parameter sets. They are not revenue forecasts.\n")

    print("| Scenario | Treatment | Control | Uplift | Distinguishable |")
    print("|---|---|---|---|---|")
    for name, scenario in scenarios.items():
        t, c = scenario["treatment"], scenario["control"]
        distinguishable = "no" if scenario["uplift_ci_overlaps"] else "yes"
        print(
            f"| {name} | {t['rate']:.1%} "
            f"[{t['rate_ci95'][0]:.1%}-{t['rate_ci95'][1]:.1%}] | "
            f"{c['rate']:.1%} [{c['rate_ci95'][0]:.1%}-{c['rate_ci95'][1]:.1%}] | "
            f"{scenario['uplift_pp']:+.1f}pp | {distinguishable} |"
        )
    print()
    print(f"Treatment n={central['treatment']['n']}, control n={central['control']['n']}. ")
    print("Intervals are Wilson 95%.\n")

    like = central["like_for_like"]
    print("### Against a contact-everyone baseline\n")
    print(f"Restricted to the {like['n']:,} cases both policies may act on unaided, so the")
    print("comparison isolates targeting rather than permission.\n")
    print("| | Reclaim | Contact everyone |")
    print("|---|---|---|")
    print(f"| Customers contacted | {like['reclaim_contacts']:,} | {like['baseline_contacts']:,} |")
    print(f"| Recovered (simulated) | {like['reclaim_recovered']:,} | {like['baseline_recovered']:,} |")
    print(f"| Revenue (simulated) | {rupees(like['reclaim_revenue_paise'])} | {rupees(like['baseline_revenue_paise'])} |")
    saved = like["baseline_contacts"] - like["reclaim_contacts"]
    gap = like["baseline_revenue_paise"] - like["reclaim_revenue_paise"]
    print()
    print("**This is a trade-off, not a win.** Contacting everyone recovers")
    print(f"{rupees(gap)} more ({gap / like['reclaim_revenue_paise']:.0%}) by sending {saved:,} more")
    print(f"messages ({saved / like['reclaim_contacts']:.0%}). Reclaim gives up some recovery to avoid")
    print("contacting people it judges unlikely to convert.")
    print()
    print("Whether that is the right call is a merchant's decision, not ours -- the floor")
    print("that produces it is a single configurable threshold. What Reclaim provides is")
    print("the ability to make that choice deliberately, and to see what it costs.")
    print()

    print("## Caveats\n")
    for caveat in report["simulated"]["caveats"]:
        print(f"- {caveat}")
    print()


if __name__ == "__main__":
    main()
